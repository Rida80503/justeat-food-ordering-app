import { createAsyncThunk, createSlice } from "@reduxjs/toolkit";
import { api } from "../../utils/api";

/**
 * Fetch restaurant details along with its menu.
 *
 * APIs:
 * 1. GET /restaurants/:restaurantId
 *    - Fetches restaurant information.
 *
 * 2. GET /menus/restaurant/:restaurantId
 *    - Fetches all menu items for the restaurant.
 *
 * Returns:
 * {
 *   restaurant: {...},
 *   menu: [...]
 * }
 */
export const fetchRestaurantDetails = createAsyncThunk(
  "menu/fetchRestaurantDetails",
  async (restaurantId, { rejectWithValue }) => {
    try {
      // Fetch restaurant information
      const restaurantResponse = await api.get(
        `/restaurants/${restaurantId}`
      );

      // Fetch menu items
      const menuResponse = await api.get(
        `/menus/restaurant/${restaurantId}`
      );

      // Return combined data
      return {
        restaurant: restaurantResponse.data.data,
        menu: menuResponse.data.data,
      };
    } catch (error) {
      return rejectWithValue(
        error.response?.data?.detail ||
        "Failed to load restaurant"
      );
    }
  }
);

/**
 * Redux Slice for Restaurant Details & Menu.
 *
 * Stores:
 * - Restaurant Information
 * - Menu Items
 * - Loading State
 * - Error State
 */
const menuSlice = createSlice({
  name: "menu",

  /**
   * Initial Redux State
   */
  initialState: {
    restaurant: null,
    menu: [],
    loading: false,
    error: null,
  },

  /**
   * No synchronous reducers are required
   * because all updates happen through
   * async API requests.
   */
  reducers: {},

  /**
   * Handles async actions generated by
   * fetchRestaurantDetails().
   */
  extraReducers: (builder) => {
    builder

      /**
       * Triggered when API request starts.
       * Shows loading indicator and clears
       * previous errors.
       */
      .addCase(fetchRestaurantDetails.pending, (state) => {
        state.loading = true;
        state.error = null;
      })

      /**
       * Triggered when both API calls
       * complete successfully.
       * Updates restaurant details and menu.
       */
      .addCase(fetchRestaurantDetails.fulfilled, (state, action) => {
        state.loading = false;

        state.restaurant = action.payload.restaurant;
        state.menu = action.payload.menu;
      })

      /**
       * Triggered when any API request fails.
       * Stores the error message.
       */
      .addCase(fetchRestaurantDetails.rejected, (state, action) => {
        state.loading = false;
        state.error = action.payload;
      });
  },
});

/**
 * Export reducer
 */
export default menuSlice.reducer;